/**
 * Represents a taxonomy entry in the built-in reference data.
 */
export interface TaxonomyEntry {
  name: string;
  rank: TaxonomicRank;
  domain: Domain;
  lineage: GTDBLineage;
  genomeCount: number;
  speciesCount: number;
  isPlaceholder?: boolean;
  description?: string;
  children?: string[];
}

/**
 * Helper to build a full lineage object from partial data.
 */
function makeLineage(
  domain: string,
  phylum: string,
  klass: string,
  order: string,
  family: string,
  genus: string,
  species: string
): GTDBLineage {
  return {
    domain: domain || undefined,
    phylum: phylum || undefined,
    class: klass || undefined,
    order: order || undefined,
    family: family || undefined,
    genus: genus || undefined,
    species: species || undefined,
  };
}

